/**
 * Runtime of the Hey API stack (ADR 0027): entry `openapi-versions/hey-api`. Same model as the
 * openapi-fetch stacks (ADR 0003): compat from /version, useSupports / useHasField / <Feature> on op
 * keys, and gate() for queries. What differs:
 *
 * - Hey API generates one module-level client (`v<n>/sdk/client.gen.ts`); the provider configures it
 *   (`setConfig({ baseUrl, fetch })`) instead of creating a client.
 * - X-Api-Version and Sunset are read by a response interceptor, not an openapi-fetch middleware.
 * - gate() reads the operation from the query key Hey API builds, `[{ _id: "getUserActivity", ... }]`,
 *   and maps it to an op key with `meta.opIds`.
 * - `$api` / `$gated` are not on `useApi()`: they are the generated `core.ts` / `gated.ts` modules,
 *   exported by `v<n>/client.ts`. For invalidation, take a key from the options:
 *   `queryClient.invalidateQueries({ queryKey: $api.getUserOptions(args).queryKey })`.
 *
 * Imports no openapi-fetch or openapi-react-query: Hey API's client is copied into the generated output,
 * so `@tanstack/react-query` (and React, for the hooks) are the only peers this entry needs.
 */
import { skipToken } from "@tanstack/react-query";
import { type CompatOptions, type MajorMeta, type OkCompat, resolveCompat } from "../core/compat";
import { type ApiHeaderHandlers, fetchBackendVersion, readApiHeaders } from "../core/version";
import { type Bindings, createBindings } from "../react/bindings";

export type { Compat, CompatOptions, MajorMeta, OkCompat } from "../core/compat";
export { API_VERSION_KEY, type ApiVersionProviderProps, type FeatureProps } from "../react/bindings";

/** meta.ts of a major generated with `generator: "hey-api"`. */
export interface HeyApiMeta extends MajorMeta {
  /** Hey API operation id (the `_id` of its query keys) -> op key ("get /users/{id}") */
  readonly opIds: Readonly<Record<string, string>>;
}

/** The part of a generated Hey API fetch client (`v<n>/sdk/client.gen.ts`) this runtime uses. */
export interface HeyApiClient {
  getConfig(): { fetch?: typeof globalThis.fetch };
  setConfig(config: { baseUrl?: string; fetch?: typeof globalThis.fetch }): unknown;
  interceptors: {
    response: {
      use(fn: (response: Response, ...rest: any[]) => Response | Promise<Response>): unknown;
    };
  };
}

/** What gate() accepts: the result of a Hey API `xxxOptions()` helper. */
export type HeyApiQueryOptions = { queryKey: readonly [{ _id: string }]; queryFn?: unknown };
/** The options with `skipToken` as a possible queryFn, so `useSuspenseQuery` rejects them. */
export type Gated<O extends HeyApiQueryOptions> = Omit<O, "queryFn"> & { queryFn: O["queryFn"] | typeof skipToken };

/** What `useApi()` and `createApi()` return. */
export interface HeyApi {
  compat: OkCompat;
  /**
   * Replace queryFn with skipToken when the connected backend lacks the operation:
   * `useQuery(gate($gated.getUserActivityOptions(args)))`.
   */
  gate<O extends HeyApiQueryOptions>(options: O): Gated<O>;
}

export function buildHeyApi(meta: HeyApiMeta, compat: OkCompat): HeyApi {
  return {
    compat,
    gate: <O extends HeyApiQueryOptions>(options: O): Gated<O> => {
      const id = options.queryKey[0]._id;
      // own keys only: "toString" must not find Object.prototype's
      const op = Object.hasOwn(meta.opIds, id) ? meta.opIds[id] : undefined;
      // codegen and the runtime disagree: a v<n>/ generated by another Hey API version, or a hand-made key
      if (!op) throw new Error(`gate(): unknown Hey API operation "${id}" (not in meta.opIds; re-run codegen)`);
      return (compat.supports(op) ? options : { ...options, queryFn: skipToken }) as Gated<O>;
    },
  };
}

/** Per generated client, module-level so HMR re-running `v<n>/client.ts` finds the same entry. */
interface ClientState {
  /** the fetch the app configured on the client (createClientConfig, setConfig) before we touched it */
  appFetch: typeof globalThis.fetch | undefined;
  /** the header handlers of every mounted provider; one interceptor forwards to all of them */
  listeners: Set<ApiHeaderHandlers>;
}
const states = new WeakMap<HeyApiClient, ClientState>();

function stateOf(client: HeyApiClient): ClientState {
  let state = states.get(client);
  if (!state) {
    state = { appFetch: client.getConfig().fetch, listeners: new Set() };
    const { listeners } = state;
    client.interceptors.response.use((response) => {
      for (const handlers of listeners) readApiHeaders(response, handlers);
      return response;
    });
    states.set(client, state);
  }
  return state;
}

/**
 * Points the generated client at `baseUrl`, and at `fetch` when given; without one, back to the fetch the
 * app configured on the client, if any. The client is module-level: this re-points every user of it.
 */
export function connectClient(client: HeyApiClient, { baseUrl, fetch }: { baseUrl: string; fetch?: typeof globalThis.fetch }): void {
  const { appFetch } = stateOf(client);
  client.setConfig({ baseUrl, fetch: fetch ?? appFetch ?? ((input, init) => globalThis.fetch(input, init)) });
}

/** Forwards X-Api-Version and Sunset of every response of the client to `handlers`. Returns the cleanup. */
export function listenClient(client: HeyApiClient, handlers: ApiHeaderHandlers): () => void {
  const { listeners } = stateOf(client);
  listeners.add(handlers);
  return () => listeners.delete(handlers);
}

export type CreateHeyApiOptions = { baseUrl: string; fetch?: typeof globalThis.fetch } & CompatOptions;

/** What the generated `v<n>/client.ts` destructures. `G` = gated op keys, `F` = gated field keys. */
export interface HeyApiAware<G extends string, F extends string> extends Bindings<HeyApi, G, F> {
  /** Framework-free (loaders, scripts): configures the generated client, resolves compat, throws if unsupported. */
  createApi: (opts: CreateHeyApiOptions) => Promise<HeyApi>;
}

/** Binds the runtime to one generated major and its Hey API client. Called by the generated `v<n>/client.ts`. */
export function createHeyApiAware<G extends string, F extends string>(meta: HeyApiMeta, client: HeyApiClient): HeyApiAware<G, F> {
  const bindings = createBindings<HeyApiClient, HeyApi, G, F>(meta, {
    connect(opts) {
      connectClient(client, opts);
      return client;
    },
    // Hey API reads its interceptor list when a response arrives, so registering in an effect is in time
    listen: listenClient,
    build: (compat) => buildHeyApi(meta, compat),
  });

  async function createApi(opts: CreateHeyApiOptions): Promise<HeyApi> {
    const compat = resolveCompat(await fetchBackendVersion(opts.baseUrl, opts.fetch), { [meta.major]: meta }, opts);
    if (compat.status !== "ok") throw new Error(`Unsupported backend: ${compat.status} (${compat.version})`);
    connectClient(client, opts);
    return buildHeyApi(meta, compat);
  }

  return { ...bindings, createApi };
}
