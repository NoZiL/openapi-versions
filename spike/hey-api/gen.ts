/**
 * Spike #124: the Hey API generator path, as a post-step on what `pnpm codegen` already wrote.
 * Not wired into codegen/build.ts (that is #125). For each target:
 *
 *   1. run @hey-api/openapi-ts on `merged.openapi.json` (client-fetch, typescript with open enums, sdk, TanStack Query)
 *      into `v<n>/sdk/`: Hey API writes a `client/` folder and imports it as `./client`, which our
 *      `v<n>/client.ts` would shadow if both lived in one folder
 *   2. read back, from Hey API's own symbol registry, the exported name of every per-operation function
 *      (sdk function, queryOptions, mutationOptions, ...) and the operation's `method /path`
 *   3. write, next to Hey API's output:
 *        meta.ts   our meta + `opIds` (Hey API operation id -> op key), what gate() reads
 *        core.ts   re-exports of the floor operations only
 *        gated.ts  re-exports of the operations added after the floor
 *        client.ts what apps import: runtime bound to this major + `$api` (core) and `$gated` namespaces
 *
 * Run `pnpm codegen` first, then `pnpm exec tsx spike/hey-api/gen.ts`.
 */
import fs from "node:fs";
import path from "node:path";
import { createClient } from "@hey-api/openapi-ts";
import { openEnumsHeyApi } from "./open-enums";

const HEADER = "// generated by version-aware codegen — do not edit";

const targets = [
  { generated: "playground/generated/v1", out: "spike/hey-api/out/playground/v1" },
  { generated: "test/fixtures/generated/v1", out: "spike/hey-api/out/test/v1" },
];

/** Open-enum fixtures (ADR 0019 shapes): types only, to compare with the openapi-typescript output. */
const enumFixtures = [
  { input: "test/fixtures/enum-shapes/1.0.0.json", out: "spike/hey-api/out/enum-shapes" },
  { input: "test/fixtures/enum-shapes-3.0/1.0.0.json", out: "spike/hey-api/out/enum-shapes-3.0" },
];

const plugins = [
  "@hey-api/client-fetch",
  { name: "@hey-api/typescript", $resolvers: openEnumsHeyApi },
  "@hey-api/sdk",
  "@tanstack/react-query",
] as any[];

interface OpSymbols {
  opKey: string;
  /** file (relative to the output dir, no extension) -> exported names */
  exports: Map<string, string[]>;
}

/** `relTo`: the folder the re-export paths are relative to (where core.ts and gated.ts live) */
async function generate(input: string, out: string, relTo = out): Promise<Map<string, OpSymbols>> {
  fs.rmSync(out, { recursive: true, force: true });
  const [ctx] = (await createClient({ input, output: { path: out }, logs: { level: "silent" }, plugins })) as any[];

  // Hey API names operations itself (`get-a` -> `getA`, no operationId -> `postB`, `delete` -> `delete_`
  // for the sdk function but `delete` in query keys). Ask it instead of re-deriving the names.
  const ops = new Map<string, OpSymbols>();
  for (const [p, item] of Object.entries<any>(ctx.ir.paths ?? {}))
    for (const [method, op] of Object.entries<any>(item)) if (op?.id) ops.set(op.id, { opKey: `${method} ${p}`, exports: new Map() });

  for (const s of ctx.gen.symbols.query({ resource: "operation" })) {
    if (s.meta?.category === "type" || !s.exported) continue; // types are harmless: they call nothing
    const op = ops.get(s.meta.resourceId);
    const file = s.file?.finalPath ?? s.file?.path;
    if (!op || !file) throw new Error(`symbol ${s.name} of operation ${s.meta.resourceId} has no operation or file`);
    const rel = `./${path.relative(relTo, file).replace(/\.ts$/, "")}`;
    op.exports.set(rel, [...(op.exports.get(rel) ?? []), s.finalName ?? s.name]);
  }
  return ops;
}

function reexports(ops: OpSymbols[]): string {
  const byFile = new Map<string, string[]>();
  for (const op of ops) for (const [file, names] of op.exports) byFile.set(file, [...(byFile.get(file) ?? []), ...names]);
  return [...byFile].map(([file, names]) => `export { ${names.sort().join(", ")} } from ${JSON.stringify(file)};`).join("\n");
}

for (const { generated, out } of targets) {
  fs.rmSync(out, { recursive: true, force: true });
  const ops = await generate(path.join(generated, "merged.openapi.json"), path.join(out, "sdk"), out);
  const metaSrc = fs.readFileSync(path.join(generated, "meta.ts"), "utf8");
  const meta = JSON.parse(metaSrc.match(/export const meta = ([\s\S]*?) as const;/)![1]);
  const opIds = Object.fromEntries([...ops].map(([id, o]) => [id, o.opKey]));
  for (const key of meta.ops) if (!Object.values(opIds).includes(key)) throw new Error(`no Hey API operation for ${key}`);

  const isGated = (o: OpSymbols) => o.opKey in meta.gatedOps;
  fs.writeFileSync(
    path.join(out, "meta.ts"),
    `${HEADER}\n` +
      `export const meta = ${JSON.stringify({ ...meta, opIds }, null, 2)} as const;\n\n` +
      `export type Op = (typeof meta.ops)[number];\n` +
      `export type GatedOp = keyof typeof meta.gatedOps;\n` +
      `export type GatedField = keyof typeof meta.gatedFields;\n`,
  );
  fs.writeFileSync(
    path.join(out, "core.ts"),
    `${HEADER}\n// Operations every supported backend has (floor and older): call them directly.\n${reexports([...ops.values()].filter((o) => !isGated(o)))}\n`,
  );
  fs.writeFileSync(
    path.join(out, "gated.ts"),
    `${HEADER}\n// Operations added after the floor: queries go through gate(), mutations are rendered inside <Feature>.\n${reexports([...ops.values()].filter(isGated))}\n`,
  );
  const runtimeImport = path.relative(out, "spike/hey-api/runtime");
  fs.writeFileSync(
    path.join(out, "client.ts"),
    `${HEADER}\n` +
      `import { createHeyApiAware } from ${JSON.stringify(runtimeImport)};\n` +
      `import { client } from "./sdk/client.gen";\n` +
      `import { meta, type GatedOp, type GatedField } from "./meta";\n\n` +
      `const runtime = createHeyApiAware<GatedOp, GatedField>(meta, client);\n\n` +
      `export const { ApiVersionProvider, useApi, useSupports, useHasField, useSunset, Feature, createApi } = runtime;\n` +
      `/** floor operations: sdk functions, xxxOptions(), xxxMutation() */\n` +
      `export * as $api from "./core";\n` +
      `/** newer operations: useQuery(gate($gated.xxxOptions(...))), $gated.xxxMutation() inside <Feature> */\n` +
      `export * as $gated from "./gated";\n` +
      `export type * from "./sdk/types.gen";\n` +
      `export type { GatedOp, GatedField };\n` +
      `export type Api = ReturnType<typeof useApi>;\n`,
  );
  console.log(`gen ${out}: ${ops.size} ops, ${[...ops.values()].filter(isGated).length} gated`);
}

for (const { input, out } of enumFixtures) {
  await generate(input, out);
  console.log(`gen ${out}`);
}
